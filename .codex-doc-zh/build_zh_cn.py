def set_chinese_font(run) -> None:
    r_pr = run._element.get_or_add_rPr()
    r_fonts = r_pr.rFonts
    if r_fonts is None:
        r_fonts = OxmlElement("w:rFonts")
        r_pr.insert(0, r_fonts)
    r_fonts.set(qn("w:eastAsia"), "Microsoft YaHei")
    lang = r_pr.find(qn("w:lang"))
    if lang is None:
        lang = OxmlElement("w:lang")
        r_pr.append(lang)
    lang.set(qn("w:eastAsia"), "zh-CN")


def nonempty_runs(paragraph):
    return [run for run in paragraph.runs if run.text]


def replace_paragraph(index: int, paragraph) -> None:
    if index not in TRANSLATIONS:
        return
    runs = nonempty_runs(paragraph)
    if index in RUN_TRANSLATIONS:
        replacements = RUN_TRANSLATIONS[index]
        if len(runs) != len(replacements):
            raise RuntimeError(
                f"Paragraph {index}: expected {len(replacements)} text runs, found {len(runs)}"
            )
        for run, text in zip(runs, replacements, strict=True):
            run.text = text
            set_chinese_font(run)
        return

    if not runs:
        run = paragraph.add_run(TRANSLATIONS[index])
        set_chinese_font(run)
        return
    runs[0].text = TRANSLATIONS[index]
    set_chinese_font(runs[0])
    for run in runs[1:]:
        run.text = ""


def replace_cell_text(cell, text: str) -> None:
    paragraph = cell.paragraphs[0]
    runs = nonempty_runs(paragraph)
    if runs:
        runs[0].text = text
        set_chinese_font(runs[0])
        for run in runs[1:]:
            run.text = ""
    else:
        run = paragraph.add_run(text)
        set_chinese_font(run)


def translate_header_footer(document: Document) -> None:
    for section in document.sections:
        # Access only the header/footer parts that already exist in the source.
        # Accessing first/even variants through python-docx would create new parts.
        for container in (section.header,):
            for paragraph in container.paragraphs:
                for run in paragraph.runs:
                    if "KẾ HOẠCH TRIỂN KHAI V1" in run.text:
                        run.text = run.text.replace("KẾ HOẠCH TRIỂN KHAI V1", "V1实施计划")
                        set_chinese_font(run)
        for container in (section.footer,):
            for paragraph in container.paragraphs:
                for run in paragraph.runs:
                    if "Trang " in run.text:
                        run.text = run.text.replace("Trang ", "页码 ")
                        set_chinese_font(run)


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("Usage: build_zh_cn.py SOURCE.docx OUTPUT.docx")
    source = Path(sys.argv[1]).resolve()
    output = Path(sys.argv[2]).resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, output)

    document = Document(output)
    source_nonempty = {
        index for index, paragraph in enumerate(document.paragraphs) if paragraph.text.strip()
    }
    missing = sorted(source_nonempty - set(TRANSLATIONS))
    extra = sorted(set(TRANSLATIONS) - source_nonempty)
    if missing or extra:
        raise RuntimeError(f"Translation coverage mismatch: missing={missing}, extra={extra}")

    for index, paragraph in enumerate(document.paragraphs):
        replace_paragraph(index, paragraph)

    if len(document.tables) != 1:
        raise RuntimeError(f"Expected one table, found {len(document.tables)}")
    table = document.tables[0]
    if len(table.rows) != len(TABLE_TRANSLATIONS):
        raise RuntimeError("Unexpected table row count")
    for row, translated_row in zip(table.rows, TABLE_TRANSLATIONS, strict=True):
        if len(row.cells) != len(translated_row):
            raise RuntimeError("Unexpected table column count")
        for cell, text in zip(row.cells, translated_row, strict=True):
            replace_cell_text(cell, text)

    translate_header_footer(document)
    document.core_properties.title = "V1版本实施计划"
    document.core_properties.subject = "AI沟通助手 - Flutter Android与Next.js后端"
    document.save(output)

    # Reopen immediately so malformed OOXML fails during the build.
    reopened = Document(output)
    if len(reopened.paragraphs) != len(document.paragraphs):
        raise RuntimeError("Paragraph count changed after saving")


if __name__ == "__main__":
    main()
